"""
Custom evaluator for the coaching-eval-lab: warmth/empathy.

LLM-as-judge, scored 1-5, measuring whether the coach's response feels
human and validating rather than clinical/interrogative — independent
of correctness (structure/advice-giving), which is scored separately
in evaluator.py. A response can pass correctness and still score low
here if it reads as cold or checklist-like.

Used alongside coaching_correctness_evaluator in evaluation_run.py.
"""

import json

from dotenv import load_dotenv
from langsmith import traceable
from langsmith.wrappers import wrap_openai
from openai import OpenAI

load_dotenv()

openai_client = wrap_openai(OpenAI())

WARMTH_JUDGE_SYSTEM_PROMPT = """You are grading a workplace coaching AI's response for warmth \
and empathy — NOT for structure or correctness (that is scored separately).

You will be given the employee's latest message (and prior conversation history, if any) and \
the coach's generated response.

Score the response on a 1-5 scale for how warm, human, and validating it feels — independent of \
whether it is structurally a single clean question:

5 = Warm acknowledgment of what the employee said, phrased like someone who was really \
listening; feels validating before or within the question.
4 = Mostly warm, slightly more neutral in phrasing but still feels attentive.
3 = Neutral / professional — neither warm nor cold, purely functional.
2 = Somewhat clinical or interrogative, feels slightly like a checklist question.
1 = Clinical, interrogative, or robotic — feels like a form question with no acknowledgment of \
what the employee shared.

Do NOT penalize the response for being a single clean question — that is a separate dimension. \
Judge tone and human warmth only.

Respond with ONLY a JSON object, no other text, in this exact format:
{"score": 1-5, "reasoning": "one short sentence explaining the score"}"""


def _format_history(conversation_history: list) -> str:
    if not conversation_history:
        return "(This is the first message in the conversation.)"
    lines = [f"{turn['role'].upper()}: {turn['text']}" for turn in conversation_history]
    return "\n".join(lines)


@traceable(name="warmth_evaluator")
def warmth_evaluator(inputs: dict, outputs: dict, reference_outputs: dict = None) -> dict:
    """
    LangSmith custom evaluator function.

    inputs: {"conversation_history": [...], "latest_message": "..."}
    outputs: {"expected_output": "..."}  # generated by the target function
    reference_outputs: unused here — warmth is judged independent of the
                        reference, since the reference itself is not
                        scored for warmth

    returns: {"key": "warmth", "score": 1-5, "comment": "..."}
    """
    try:
        history_text = _format_history(inputs.get("conversation_history", []))
        latest_message = inputs["latest_message"]
        generated_response = outputs.get("expected_output", "")

        user_content = (
            f"Conversation so far:\n{history_text}\n\n"
            f"EMPLOYEE: {latest_message}\n\n"
            f"Generated coach response to grade: {generated_response}\n\n"
            f"Grade the warmth of this response."
        )

        response = openai_client.chat.completions.create(
            model="gpt-4o-mini",
            temperature=0,
            response_format={"type": "json_object"},
            messages=[
                {"role": "system", "content": WARMTH_JUDGE_SYSTEM_PROMPT},
                {"role": "user", "content": user_content},
            ],
        )
        result = json.loads(response.choices[0].message.content)

        return {
            "key": "warmth",
            "score": int(result["score"]),
            "comment": result.get("reasoning", ""),
        }

    except Exception as e:
        return {"key": "warmth", "score": 0, "comment": f"[EVALUATOR ERROR: {e}]"}


if __name__ == "__main__":
    # Quick manual test: grade the 3 target_function.py test outputs for warmth
    test_cases = [
        {
            "inputs": {"conversation_history": [], "latest_message": "I want to be a manager within two years."},
            "outputs": {"expected_output": "What specific skills or experiences do you believe you need to develop in order to reach that managerial position?"},
        },
        {
            "inputs": {
                "conversation_history": [
                    {"role": "employee", "text": "I already tried setting goals before and it didn't work."},
                    {"role": "coach", "text": "What got in the way last time?"},
                ],
                "latest_message": "Honestly, I just lost interest after a few weeks.",
            },
            "outputs": {"expected_output": "What do you think contributed to losing interest in your goals?"},
        },
        {
            "inputs": {"conversation_history": [], "latest_message": "I don't need coaching, I already know what I'm doing wrong."},
            "outputs": {"expected_output": "What do you believe is the most significant barrier to making the changes you want to see?"},
        },
    ]

    for i, case in enumerate(test_cases, 1):
        result = warmth_evaluator(case["inputs"], case["outputs"])
        print(f"--- Test {i} ---")
        print(f"Warmth score: {result['score']} | Comment: {result['comment']}\n")
