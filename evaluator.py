"""
Correctness evaluator for the coaching-eval-lab.

LLM-as-judge: scores whether the target function's generated coach
response is coaching-appropriate (single open question, no advice, no
compound questions, reasonable given context) — not whether it matches
the reference expected_output word-for-word, since there's no single
"correct" question in coaching.

Used as an evaluator in evaluation_run.py.
"""

import json

from dotenv import load_dotenv
from langsmith import traceable
from langsmith.wrappers import wrap_openai
from openai import OpenAI

load_dotenv()

openai_client = wrap_openai(OpenAI())

JUDGE_SYSTEM_PROMPT = """You are grading a workplace coaching AI's response for quality.

You will be given:
- The employee's latest message (and prior conversation history, if any)
- A reference example of a good coach response (for context on the right spirit/tone \
— the generated response does NOT need to match it word-for-word)
- The generated coach response to grade

Score the generated response PASS (1) only if ALL of these are true:
1. It is exactly ONE question — not a compound/double-barreled question (e.g. "is it X, \
or is it Y" fails this).
2. It is open-ended — not answerable with a simple yes/no.
3. It contains no advice, suggestions, solutions, or opinions — only a question.
4. It is a reasonable, relevant reflective follow-up given the employee's message and \
conversation history (does not have to match the reference exactly).

If ANY of these fail, score FAIL (0).

Respond with ONLY a JSON object, no other text, in this exact format:
{"score": 0 or 1, "reasoning": "one short sentence explaining the score"}"""


def _format_history(conversation_history: list) -> str:
    if not conversation_history:
        return "(This is the first message in the conversation.)"
    lines = [f"{turn['role'].upper()}: {turn['text']}" for turn in conversation_history]
    return "\n".join(lines)


@traceable(name="coaching_correctness_evaluator")
def coaching_correctness_evaluator(inputs: dict, outputs: dict, reference_outputs: dict) -> dict:
    """
    LangSmith evaluator function.

    inputs: {"conversation_history": [...], "latest_message": "..."}
    outputs: {"expected_output": "..."}          # generated by the target function
    reference_outputs: {"expected_output": "..."} # from the dataset

    returns: {"key": "correctness", "score": 0 or 1, "comment": "..."}
    """
    try:
        history_text = _format_history(inputs.get("conversation_history", []))
        latest_message = inputs["latest_message"]
        generated_response = outputs.get("expected_output", "")
        reference_response = reference_outputs.get("expected_output", "")

        user_content = (
            f"Conversation so far:\n{history_text}\n\n"
            f"EMPLOYEE: {latest_message}\n\n"
            f"Reference good response (for spirit/tone only): {reference_response}\n\n"
            f"Generated response to grade: {generated_response}\n\n"
            f"Grade the generated response."
        )

        response = openai_client.chat.completions.create(
            model="gpt-4o-mini",
            temperature=0,
            response_format={"type": "json_object"},
            messages=[
                {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                {"role": "user", "content": user_content},
            ],
        )
        result = json.loads(response.choices[0].message.content)

        return {
            "key": "correctness",
            "score": int(result["score"]),
            "comment": result.get("reasoning", ""),
        }

    except Exception as e:
        # If the judge call itself fails, surface it as a 0 with the error
        # visible in the comment rather than crashing the whole eval run.
        return {"key": "correctness", "score": 0, "comment": f"[EVALUATOR ERROR: {e}]"}


if __name__ == "__main__":
    # Quick manual test: grade the 3 target_function.py test outputs directly
    test_cases = [
        {
            "inputs": {"conversation_history": [], "latest_message": "I want to be a manager within two years."},
            "outputs": {"expected_output": "What specific skills or experiences do you believe you need to develop in order to reach that managerial position?"},
            "reference_outputs": {"expected_output": "What draws you to management specifically?"},
        },
        {
            "inputs": {
                "conversation_history": [
                    {"role": "employee", "text": "I already tried setting goals before and it didn't work."},
                    {"role": "coach", "text": "What got in the way last time?"},
                ],
                "latest_message": "Honestly, I just lost interest after a few weeks.",
            },
            "outputs": {"expected_output": "What do you think contributed to losing interest in your goals?"},
            "reference_outputs": {"expected_output": "What was different about the moment you lost interest, compared to when you first set the goal?"},
        },
    ]

    for i, case in enumerate(test_cases, 1):
        result = coaching_correctness_evaluator(
            case["inputs"], case["outputs"], case["reference_outputs"]
        )
        print(f"--- Test {i} ---")
        print(f"Score: {result['score']} | Comment: {result['comment']}\n")
